using Layer = volumetric_base::Layer;

// =====================================================================================================================

// ---------------------------------------------------------------------------------------------------------------------

DualQuaternionSkinning::DualQuaternionSkinning() : LinearBlendSkinning()
{
}

// ---------------------------------------------------------------------------------------------------------------------

DualQuaternionSkinning::~DualQuaternionSkinning() = default;

// ---------------------------------------------------------------------------------------------------------------------

void DualQuaternionSkinning::updated_pose(volumetric_base::VolumetricState* state)
{
    if (state == nullptr) {
        return;
    }

    // perform Dual quaternion skinning for all layers
    volumetric_base::skinning::dqs(state, _result_skel, Layer::SKEL);
    volumetric_base::skinning::dqs(state, _result_musc, Layer::MUSC);
    volumetric_base::skinning::dqs(state, _result_skin, Layer::SKIN);
}

